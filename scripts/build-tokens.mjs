// Builds the token library from /tokens/*.json (W3C design-token format) into:
//   src/design-system/tokens/tokens.css   CSS custom properties; aliases stay live as var() references
//   src/design-system/tokens/tokens.ts    typed token list + helpers for components, docs and Storybook
//   src/design-system/tokens/tokens.json  flat, fully resolved values for other tools (Figma, native)
//
// Naming: a token's path joined with "-" becomes its CSS variable; a "default" key is dropped,
// so text.default → --text and text.secondary → --text-secondary.

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'tokens')
const outDir = join(root, 'src/design-system/tokens')

const files = readdirSync(srcDir)
  .filter((f) => f.endsWith('.json'))
  .sort((a, b) => order(a) - order(b))

function order(file) {
  const rank = ['color.primitives', 'color.semantic', 'typography', 'layout', 'effects']
  const i = rank.indexOf(basename(file, '.json'))
  return i === -1 ? rank.length : i
}

const tokens = []
const groups = []

for (const file of files) {
  const stem = basename(file, '.json')
  const [category, tierHint] = stem.split('.')
  const tier = tierHint === 'semantic' ? 'semantic' : 'primitive'
  const tree = JSON.parse(readFileSync(join(srcDir, file), 'utf8'))
  walk(tree, [], undefined, { category, tier })
}

function walk(node, path, inheritedType, meta) {
  const type = node.$type ?? inheritedType
  if ('$value' in node) {
    tokens.push({
      name: cssName(path),
      path,
      type,
      raw: String(node.$value),
      description: node.$description,
      category: meta.category,
      tier: meta.tier,
    })
    return
  }
  if (path.length) {
    groups.push({ name: cssName(path), path, type, description: node.$description, category: meta.category, tier: meta.tier })
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    walk(child, [...path, key], type, meta)
  }
}

function cssName(path) {
  return path.filter((p) => p !== 'default').join('-')
}

// ── resolve aliases ───────────────────────────────────────────
const byRef = new Map(tokens.map((t) => [t.path.join('.'), t]))
const seen = new Set()
for (const t of tokens) {
  if (seen.has(t.name)) throw new Error(`Duplicate token name --${t.name}`)
  seen.add(t.name)
}

function resolve(t, stack = []) {
  const m = t.raw.match(/^\{(.+)\}$/)
  if (!m) return t.raw
  const target = byRef.get(m[1]) ?? byRef.get(`${m[1]}.default`)
  if (!target) throw new Error(`--${t.name} references unknown token {${m[1]}}`)
  if (stack.includes(target.name)) throw new Error(`Circular alias: ${[...stack, target.name].join(' → ')}`)
  return resolve(target, [...stack, t.name])
}

for (const t of tokens) {
  const m = t.raw.match(/^\{(.+)\}$/)
  if (m) {
    const target = byRef.get(m[1]) ?? byRef.get(`${m[1]}.default`)
    t.alias = target.name
    t.css = `var(--${target.name})`
  } else {
    t.css = t.raw
  }
  t.resolved = resolve(t)
}

// ── emit ──────────────────────────────────────────────────────
mkdirSync(outDir, { recursive: true })
const banner = 'Generated by scripts/build-tokens.mjs from /tokens — do not edit by hand.'

const cssLines = []
let lastCategory = ''
for (const t of tokens) {
  const heading = `${t.category} · ${t.tier}`
  if (heading !== lastCategory) {
    cssLines.push('', `  /* ${heading} */`)
    lastCategory = heading
  }
  cssLines.push(`  --${t.name}: ${t.css};`)
}
writeFileSync(join(outDir, 'tokens.css'), `/* ${banner} */\n\n:root {${cssLines.join('\n')}\n}\n`)

const tsTokens = tokens.map((t) => ({
  name: t.name,
  path: t.path,
  cssVar: `--${t.name}`,
  type: t.type,
  category: t.category,
  tier: t.tier,
  value: t.raw,
  resolved: t.resolved,
  ...(t.alias ? { alias: t.alias } : {}),
  ...(t.description ? { description: t.description } : {}),
}))

const tsGroups = groups.map((g) => ({
  name: g.name,
  path: g.path,
  type: g.type,
  category: g.category,
  tier: g.tier,
  ...(g.description ? { description: g.description } : {}),
}))

const ts = `// ${banner}

export type TokenTier = 'primitive' | 'semantic'

export type Token = {
  name: string
  path: readonly string[]
  cssVar: string
  type: string
  category: string
  tier: TokenTier
  /** Value as authored — may be an alias like {mint.400}. */
  value: string
  /** Final value after following aliases. */
  resolved: string
  /** Name of the token this one points at. */
  alias?: string
  description?: string
}

export type TokenGroup = {
  name: string
  path: readonly string[]
  type: string
  category: string
  tier: TokenTier
  description?: string
}

export const tokens = ${JSON.stringify(tsTokens, null, 2)} as const satisfies readonly Token[]

export const tokenGroups = ${JSON.stringify(tsGroups, null, 2)} as const satisfies readonly TokenGroup[]

export type TokenName = (typeof tokens)[number]['name']

/** \`var(--name)\` for use in inline styles and CSS-in-JS. */
export function cssVar(name: TokenName): string {
  return \`var(--\${name})\`
}

const resolvedByName = new Map<string, string>(tokens.map((t) => [t.name, t.resolved]))

/** The final literal value of a token, e.g. tokenValue('accent') → '#62E8B3'. */
export function tokenValue(name: TokenName): string {
  return resolvedByName.get(name) as string
}

/** Tokens whose path starts with the given group path, e.g. tokensIn('mint'). */
export function tokensIn(...groupPath: string[]): Token[] {
  return tokens.filter((t) => groupPath.every((p, i) => t.path[i] === p) && t.path.length > groupPath.length) as Token[]
}

export function groupInfo(...groupPath: string[]): TokenGroup | undefined {
  return tokenGroups.find((g) => g.path.length === groupPath.length && groupPath.every((p, i) => g.path[i] === p)) as TokenGroup | undefined
}
`
writeFileSync(join(outDir, 'tokens.ts'), ts)

const flat = Object.fromEntries(tokens.map((t) => [t.name, t.resolved]))
writeFileSync(join(outDir, 'tokens.json'), JSON.stringify(flat, null, 2) + '\n')

console.log(`tokens: ${tokens.length} tokens in ${groups.length} groups → src/design-system/tokens/{tokens.css,tokens.ts,tokens.json}`)
